#!/usr/bin/env python3
"""
gen-browser-themes.py — generate userChrome.css (Firefox + Thunderbird) and
userContent.css (Firefox only) for all four theme families (Litho, Vellum,
Daguerre, Verdigris) x two variants (dark, light), from the exact same
role-based palette every other app in this repo already uses.

Palette values are imported directly from scheme_wallpaper.py's PALETTES
dict (both are Python, so there's no reason to hand-copy 8 x 14 hex values
a second time the way the CSS/Qt/vim configs necessarily do).

Output layout (mirrors swaywm/<family>/{dark,light}):
  firefox/<family>/<variant>/userChrome.css
  firefox/<family>/<variant>/userContent.css
  thunderbird/<family>/<variant>/userChrome.css

Re-run this after changing a palette in scheme_wallpaper.py; it always
regenerates every variant from scratch.

Usage:
  gen-browser-themes.py
"""

import importlib.util
import sys
from pathlib import Path

REPO = Path.home() / ".cfg-tzevaot"
SCHEME_WALLPAPER = REPO / "bin" / "scheme_wallpaper.py"

spec = importlib.util.spec_from_file_location("scheme_wallpaper", SCHEME_WALLPAPER)
scheme_wallpaper = importlib.util.module_from_spec(spec)
spec.loader.exec_module(scheme_wallpaper)
PALETTES = scheme_wallpaper.PALETTES

FAMILIES = ["litho", "vellum", "daguerre", "verdigris"]
VARIANTS = ["dark", "light"]


def vars_block(pal: dict) -> str:
    return "\n".join(f"  --{k.replace('_', '-')}: #{v};" for k, v in pal.items())


