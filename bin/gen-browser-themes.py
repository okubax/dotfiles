def title_for(family: str, variant: str) -> str:
    return f"{family.capitalize()} {variant.capitalize()}"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print(f"  wrote {path.relative_to(REPO)}")


def main() -> int:
    for family in FAMILIES:
        for variant in VARIANTS:
            key = f"{family}_{variant}"
            pal = PALETTES[key]
            title = title_for(family, variant)
            vars_ = vars_block(pal)

            write(
                REPO / "firefox" / family / variant / "userChrome.css",
                FIREFOX_USERCHROME_TMPL.format(
                    title=title, palette_key=key, vars=vars_,
                    bg_header=pal["bg_header"], fg=pal["fg"], bg_panel_alt=pal["bg_panel_alt"],
                ),
            )
            write(
                REPO / "firefox" / family / variant / "userContent.css",
                FIREFOX_USERCONTENT_TMPL.format(title=title, bg=pal["bg"], fg=pal["fg"]),
            )
            write(
                REPO / "thunderbird" / family / variant / "userChrome.css",
                THUNDERBIRD_USERCHROME_TMPL.format(
                    title=title, palette_key=key, vars=vars_,
                    bg_header=pal["bg_header"], fg=pal["fg"], bg_panel_alt=pal["bg_panel_alt"],
                ),
            )

    print(f"\nGenerated {len(FAMILIES) * len(VARIANTS)} variants for firefox/ and thunderbird/.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
